"""Convert one-row-per-legal-move SFT data into canonical all-moves targets."""

import argparse
import json
import os
from typing import Dict, Iterable, Optional


def make_all_legal_moves_instruction(fen: str) -> str:
    return (
        "You are playing chess. Given this position in FEN, output every legal move "
        "in UCI notation, sorted lexicographically.\n"
        f"FEN: {fen}\n\n"
        "Respond with ONLY the UCI moves separated by single spaces, such as "
        "a2a3 a2a4 b1a3 b1c3."
    )


def _rows(path: str) -> Iterable[Dict]:
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                yield json.loads(line)


def _make_record(template: Dict, moves: set) -> Dict:
    ordered_moves = sorted(moves)
    return {
        "puzzle_id": template.get("puzzle_id"),
        "source_game_id": template.get("source_game_id"),
        "instruction": make_all_legal_moves_instruction(template["fen"]),
        "input": "",
        "fen": template["fen"],
        "output": " ".join(ordered_moves),
        "legal_moves": ordered_moves,
        "legal_move_count": len(ordered_moves),
        "solution_uci": template.get("solution_uci"),
        "rating": template.get("rating"),
        "rating_bucket": template.get("rating_bucket"),
        "theme_bucket": template.get("theme_bucket"),
        "themes": template.get("themes", []),
    }


def build_all_moves_dataset(source_path: str, output_path: str, max_legal_moves: Optional[int] = 80) -> Dict:
    """Group contiguous single-move rows by FEN without loading the full SFT file."""
    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    source_rows = 0
    output_rows = 0
    skipped_positions = 0
    seen_fens = set()
    current_fen = None
    current_template = None
    current_moves = set()

    def flush(output_file) -> None:
        nonlocal output_rows, skipped_positions, current_template, current_moves
        if current_template is None:
            return
        if max_legal_moves is not None and len(current_moves) > max_legal_moves:
            skipped_positions += 1
        else:
            output_file.write(json.dumps(_make_record(current_template, current_moves), separators=(",", ":")) + "\n")
            output_rows += 1

    with open(output_path, "w", encoding="utf-8") as output_file:
        for row in _rows(source_path):
            source_rows += 1
            fen = row.get("fen")
            move = row.get("output")
            if not fen or not move:
                raise ValueError(f"Source SFT row {source_rows} is missing FEN or output.")
            if current_fen is None:
                current_fen = fen
                current_template = row
            elif fen != current_fen:
                flush(output_file)
                seen_fens.add(current_fen)
                if fen in seen_fens:
                    raise ValueError(
                        "Source rows for one FEN are not contiguous. Use the benchmark "
                        "sft_train.jsonl generated by build_benchmark_datasets.py."
                    )
                current_fen = fen
                current_template = row
                current_moves = set()
            current_moves.add(str(move))
        if current_fen is not None:
            flush(output_file)

    return {
        "source_path": os.path.abspath(source_path),
        "output_path": os.path.abspath(output_path),
        "source_rows": source_rows,
        "positions_written": output_rows,
        "positions_skipped_for_legal_move_count": skipped_positions,
        "max_legal_moves": max_legal_moves,
        "ordering": "lexicographic UCI",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Create canonical all-legal-UCI-moves SFT targets.")
    parser.add_argument("--source", required=True, help="Expanded one-row-per-legal-move SFT JSONL.")
    parser.add_argument("--output", required=True)
    parser.add_argument(
        "--max-legal-moves",
        type=int,
        default=80,
        help="Skip positions above this count so complete targets fit the training context. Set 0 for no limit.",
    )
    args = parser.parse_args()
    max_legal_moves = None if args.max_legal_moves <= 0 else args.max_legal_moves
    print(json.dumps(build_all_moves_dataset(args.source, args.output, max_legal_moves), indent=2))


if __name__ == "__main__":
    main()
